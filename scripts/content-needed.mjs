// Gate G7: lists every [PREENCHER] in content and code, with where it appears and on which page it shows.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const site = JSON.parse(readFileSync("content/site.json", "utf8"));
const pagesFor = {
  "business.email": "/contacto, /privacidade", "business.googleProfileUrl": "/avaliacoes, Home rating badge",
  "booking.policy": "/marcar, /servicos", "hygiene.steps": "Home, /sobre", "about.body": "/sobre",
  "findUs": "/como-chegar", "services": "Home, /servicos, /marcar (price and duration)", "faq": "/faq, Home (first 4)",
  "legal": "/privacidade",
};
const rows = [];
const walkJson = (v, path) => {
  if (typeof v === "string") {
    if (v.includes("[PREENCHER")) {
      let page = Object.entries(pagesFor).find(([k]) => path.startsWith(k))?.[1] ?? "";
      const fi = path.match(/^faq\[(\d+)\]/);
      if (fi && Number(fi[1]) >= 4) page = "/faq";
      rows.push([`content/site.json`, path, v.replace(/\|/g, "/"), page]);
    }
  } else if (Array.isArray(v)) v.forEach((x, i) => walkJson(x, `${path}[${i}]`));
  else if (v && typeof v === "object") for (const [k, x] of Object.entries(v)) walkJson(x, path ? `${path}.${k}` : k);
};
const { _readme, ...content } = site;
walkJson(content, "");

const code = [];
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    if (!/\.tsx?$/.test(p)) continue;
    readFileSync(p, "utf8").split("\n").forEach((line, i) => {
      const m = line.match(/\[PREENCHER[^\]]*\]/g);
      if (m && !p.endsWith("Fill.tsx") && !p.endsWith("content.ts")) m.forEach((x) => code.push([`${p}:${i + 1}`, p.endsWith("ui.tsx") ? "Photo placeholder marker (see Photos below)" : x]));
    });
  }
};
["app", "components"].forEach(walk);

const out = [
  "# CONTENT NEEDED", "",
  "Generated by `npm run check:content` from `content/site.json` and the code. Every item below shows on the preview as a yellow [PREENCHER] mark.", "",
  `## In content/site.json (${rows.length})`, "", "| # | JSON path | What is needed | Shows on |", "|---|---|---|---|",
  ...rows.map((r, i) => `| ${i + 1} | \`${r[1]}\` | ${r[2]} | ${r[3]} |`), "",
  `## In code (${code.length})`, "", "| # | File:line | What is needed |", "|---|---|---|",
  ...code.map((r, i) => `| ${i + 1} | \`${r[0]}\` | ${r[1]} |`), "",
  "## Photos (placeholders marked FOTO REAL)", "",
  "Real photos only, never AI generated. Placeholders in: Home hero (4:5 vertical, hands at work), Home and /sobre portrait, /galeria 6 slots (manicure natural, verniz gel, unhas de gel, pedicure sem agua, cuticulas, antes e depois), /como-chegar building front and Gabinete 2 door.", "",
  "## Texts to validate with Veronica (written from the brief, not marked)", "",
  "- Service one line summaries in `services[].summary`.",
  "- FAQ answers on waterless pedicure and on verniz gel vs unhas de gel.",
  "- About lead paragraph and hero line.", "",
];
writeFileSync("docs/CONTENT-NEEDED.md", out.join("\n"));
console.log(`site.json: ${rows.length}, code: ${code.length}`);
